"The [h]igh level [o]peration [p]review class."

import abc
import copy
import dataclasses as dcls
import typing
from collections import abc as cabc

import tensordict as td
import torch

from aioway._utils import (
    AnyDict,
    AnySet,
    DagNode,
    decomp_dcls_members,
    decomp_replace,
    topo_sort,
)
from aioway.attrs import Attr, AttrDict

__all__ = ["Hop", "TensorHop", "TdictHop", "ListHop", "hop_dcls"]


@typing.dataclass_transform()
def hop_dcls(cls: type):
    return dcls.dataclass(match_args=False)(cls)


@hop_dcls
class Hop[T](cabc.Iterable[T], abc.ABC):
    """
    The class that defines [h]igh level [op]erations.
    It produces iterators that computes the desired batch, represented by the node.

    `Hop` is the node that would be evaluated during run time.
    It will output `torch.Tensor` a container that makes up of them.
    """

    def __hash__(self) -> int:
        return id(self)

    @typing.final
    def __iter__(self):
        # Every iteration should yield a new `Iterator`.
        from .iters import HopIter

        return HopIter(self)

    @abc.abstractmethod
    def iterate(self) -> cabc.Iterator[T]:
        """
        The iteration logic.
        Should invoke dependencies' via `__iter__` methods (just use `for` loops).
        """

        raise NotImplementedError

    @property
    def requires_grad(self) -> bool:
        """
        Whether or not the `torch.Tensor`s generated by this `Hop` `requires_grad`.
        If `False`, much like `torch`'s `requires_grad`,
        gradient does not need to propagate to this node, and we can do a graph break.

        Defaults to checking if any of the `self.deps()` have any `requires_grad`.
        """

        return any(hop.requires_grad for hop in self.deps())

    def replace(
        self,
        function: cabc.Callable[[Hop], Hop],
        memo: AnyDict[typing.Any, typing.Any] | None = None,
    ) -> typing.Self:
        """
        Replace the current `node` with `function(node)` if it's not `None`,
        or else recursively invoke `.replace(function)` on `Hop` in `.inputs()`.

        Args:
            function: The function to apply to the graph.
            memo: The memo to use if given.
        """

        def maybe_replace(hop):
            if not isinstance(hop, Hop):
                return NotImplemented

            return function(hop)

        result: typing.Any = decomp_replace(self, maybe_replace, memo=memo)
        assert type(result) == type(self)
        return result

    def rebuild(self):
        """
        Rebuild the current `Hop`. This is useful when you are switching contexts,
        e.g. switching on real mode after configuring the `HopDag` in fake mode.

        If `self._rebuild()` is not overwritten, defaults to shallow copying `self`.
        """

        copied = self._rebuild()
        assert copied is not self
        return copied

    def _rebuild(self) -> typing.Self:
        return copy.copy(self)

    def deps(self) -> cabc.Iterator[Hop]:
        "Decompose `self`, get the immediate dependencies."

        for hop in decomp_dcls_members(self, Hop):
            yield hop

    def nodes(self) -> AnySet[Hop]:
        "Get all the nodes recursively, including `self`."

        nodes = AnySet[Hop](Hop)

        # Add nodes recursively.
        def _visit_nodes(hop: Hop):
            if hop in nodes:
                return

            nodes.add(hop)

            for dep in hop.deps():
                _visit_nodes(dep)

        _visit_nodes(self)
        return nodes

    @property
    def is_source(self) -> bool:
        "If the `Hop` is not dependent on other `Hop`s, it's considered a source."

        for _ in decomp_dcls_members(self, Hop):
            return True
        else:
            return False

    @property
    def size(self) -> int:
        """
        The length of the current stream `TdictHop`.

        This should be defined for relational algebra purposes.
        """

        return NotImplemented


@hop_dcls
class TensorHop(Hop[torch.Tensor], abc.ABC):
    """
    An iterator of batches of `torch.Tensor`.
    """

    @property
    @abc.abstractmethod
    def attr(self) -> Attr:
        """
        The schema for the current `Stream`.
        """

        raise NotImplementedError


@hop_dcls
class TdictHop(Hop[td.TensorDict], abc.ABC):
    """
    An iterator of batches of `td.TensorDict`.

    This is the core abstraction used by the relational algebra operators.
    """

    @property
    @abc.abstractmethod
    def attrs(self) -> AttrDict:
        """
        The schema for the current `Stream`.
        """

        raise NotImplementedError

    def column(self, col: str) -> TensorHop:
        from aioway.relalg import StreamColumnView

        return StreamColumnView(self, col)

    def select(self, *cols: str) -> TdictHop:
        from aioway.relalg import StreamSelectView

        return StreamSelectView(self, cols)


@hop_dcls
class ListHop(Hop[cabc.Sequence[typing.Any]]):
    "A convenient list of `Hop`s, using a pull strategy to pull in the data when called."

    hops: list[Hop]
    """
    The hop list that this `HopList` represents.
    """

    def __repr__(self) -> str:
        return repr(self.hops)

    def __len__(self) -> int:
        return len(self.hops)

    @typing.overload
    def __getitem__(self, key: int) -> Hop: ...

    @typing.overload
    def __getitem__(self, key: slice) -> typing.Self: ...

    def __getitem__(self, key):
        if isinstance(key, int):
            return self.hops[key]

        if isinstance(key, slice):
            return type(self)(self.hops[key])

        raise TypeError(f"Don't know how to handle {type(key)=}.")

    @typing.override
    def iterate(self):
        for hops in zip(*self.hops):
            yield hops

    def dag(self) -> list[Hop]:
        "Order the `Hop`s in their topological order."

        dag_nodes = [DagNode(key=hop, deps=list(hop.deps())) for hop in self.nodes()]
        return topo_sort(dag_nodes)
